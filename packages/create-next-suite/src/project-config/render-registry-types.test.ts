import { describe, expect, it } from 'vitest'

import { definePlugin } from '../plugin-definition/define-plugin.ts'
import { renderRegistryTypes } from './render-registry-types.ts'

describe('renderRegistryTypes', () => {
  it('augments the registry of create-next-suite/config with every plugin and its answers', () => {
    const plugins = [
      definePlugin({
        name: 'pino',
        title: 'pino',
        options: {
          level: {
            question: 'Which level?',
            choices: ['debug', 'info'],
            default: 'info',
          },
          pretty: { type: 'boolean', question: 'Pretty?', default: false },
        },
      }),
      definePlugin({ name: 'knip', title: 'Knip' }),
      definePlugin({
        name: 'agents-md',
        title: 'AGENTS.md',
        options: {
          tools: {
            type: 'multiselect',
            question: 'Which tools?',
            choices: [{ value: 'claude', label: 'Claude' }, 'codex'],
            default: [],
          },
        },
      }),
    ]

    expect(renderRegistryTypes(plugins)).toBe(
      [
        '// Generated by create-next-suite: the plugins next-suite.config.ts can name. Do not edit;',
        '// it is written anew whenever the project is generated.',
        'export {};',
        '',
        'declare module "create-next-suite/config" {',
        '  interface PluginRegistry {',
        '    "agents-md": {',
        '      tools: readonly ("claude" | "codex")[];',
        '    };',
        '    knip: Record<never, never>;',
        '    pino: {',
        '      level: "debug" | "info";',
        '      pretty: boolean;',
        '    };',
        '  }',
        '}',
        '',
      ].join('\n'),
    )
  })
})
