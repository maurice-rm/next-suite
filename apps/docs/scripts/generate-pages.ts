import { execFileSync } from 'node:child_process'
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'
import packageJson from 'create-next-suite/package.json' with { type: 'json' }
import type { CategoriesFile, ListedCategory, PluginManifest } from 'create-next-suite/plugin'

/** Writes the docs pages that come from create-next-suite itself: its options and its CLI help. */

type Section = CategoriesFile[number]
type SchemaNode = {
  description?: string
  type?: string | string[]
  enum?: unknown[]
  const?: unknown
  // biome-ignore lint/style/useNamingConvention: JSON Schema fixes the name of this key
  $ref?: string
  items?: SchemaNode
  additionalProperties?: SchemaNode | boolean
  properties?: Record<string, SchemaNode>
  required?: string[]
  anyOf?: SchemaNode[]
  oneOf?: SchemaNode[]
}
type RootSchema = SchemaNode & {
  // biome-ignore lint/style/useNamingConvention: JSON Schema fixes the name of this key
  $defs?: Record<string, SchemaNode>
}

const PACKAGE_ROOT = fileURLToPath(
  new URL('.', import.meta.resolve('create-next-suite/package.json')),
)
const CLI_PATH = join(PACKAGE_ROOT, packageJson.bin['create-next-suite'])
const CATEGORIES_PATH = join(PACKAGE_ROOT, 'categories.json')
const PLUGINS_PATH = join(PACKAGE_ROOT, 'plugins')
const DEFS_PREFIX = '#/$defs/'
const PLUGIN_SCHEMA_PATH = join(PACKAGE_ROOT, 'dist', 'schemas', 'plugin.json')
const MANIFEST_FILE = 'plugin.json'
const CONTENT_PATH = fileURLToPath(new URL('../content/docs/', import.meta.url))
const OPTIONS_PATH = join(CONTENT_PATH, 'options')
const NOTICE = '{/* Generated by scripts/generate-pages.ts from create-next-suite; do not edit. */}'

const readJson = <Value>(path: string): Value => JSON.parse(readFileSync(path, 'utf8')) as Value

const escapeCell = (text: string): string => text.replaceAll('|', '\\|').replaceAll('\n', ' ')

const tableOf = (headers: string[], rows: string[][]): string =>
  [headers, headers.map(() => '---'), ...rows].map((cells) => `| ${cells.join(' | ')} |`).join('\n')

const pageOf = (frontmatter: { title: string; description: string }, body: string[]): string =>
  [
    '---',
    `title: ${frontmatter.title}`,
    `description: ${frontmatter.description}`,
    '---',
    '',
    NOTICE,
    '',
    ...body,
    '',
  ].join('\n')

const loadManifests = (): PluginManifest[] =>
  readdirSync(PLUGINS_PATH).flatMap((category) =>
    readdirSync(join(PLUGINS_PATH, category)).map((plugin) =>
      readJson<PluginManifest>(join(PLUGINS_PATH, category, plugin, MANIFEST_FILE)),
    ),
  )

const slugOf = (title: string): string => title.toLowerCase().replace(/[^a-z0-9]+/g, '-')

const defaultsOf = (category: ListedCategory): string[] => {
  if (Array.isArray(category.default)) {
    return category.default
  }
  return category.default === null ? [] : [category.default]
}

const flagOf = (category: ListedCategory): string =>
  category.cardinality === 'many' ? `--${category.id} <plugins>` : `--${category.id} <plugin>`

const categorySection = (category: ListedCategory, manifests: PluginManifest[]): string => {
  const defaults = defaultsOf(category)
  const rows = manifests
    .filter((manifest) => manifest.category === category.id)
    .map((plugin) => [
      `\`${plugin.name}\``,
      escapeCell(plugin.title),
      escapeCell(plugin.description),
      defaults.includes(plugin.name) ? 'yes' : '',
    ])
  const noneHint = category.cardinality === 'one' ? '' : ` Pass \`--no-${category.id}\` for none.`
  return [
    `## ${category.question}`,
    '',
    `Flag: \`${flagOf(category)}\`.${noneHint}`,
    '',
    tableOf(['Plugin', 'Title', 'What it does', 'Default'], rows),
  ].join('\n')
}

const sectionPage = (section: Section, manifests: PluginManifest[]): string =>
  pageOf(
    {
      title: section.section,
      description: `The ${section.section} options of create-next-suite.`,
    },
    [section.categories.map((category) => categorySection(category, manifests)).join('\n\n')],
  )

const cliPage = (): string => {
  const help = execFileSync(process.execPath, [CLI_PATH, '--help'], {
    encoding: 'utf8',
    env: { ...process.env, NO_COLOR: '1' },
  })
  return pageOf({ title: 'CLI', description: 'The command line of create-next-suite.' }, [
    '```text',
    help.trimEnd(),
    '```',
  ])
}

const definitionName = (node: SchemaNode): string | undefined =>
  node.$ref?.startsWith(DEFS_PREFIX) ? node.$ref.slice(DEFS_PREFIX.length) : undefined

const typeOf = (node: SchemaNode): string => {
  const name = definitionName(node)
  if (name !== undefined) {
    return `[${name}](#${name.toLowerCase()})`
  }
  if (node.enum !== undefined) {
    return node.enum.map((value) => `\`${JSON.stringify(value)}\``).join(' | ')
  }
  if (node.const !== undefined) {
    return `\`${JSON.stringify(node.const)}\``
  }
  if (node.type === 'array') {
    return `${node.items === undefined ? 'unknown' : typeOf(node.items)}[]`
  }
  if (typeof node.additionalProperties === 'object') {
    return `map of ${typeOf(node.additionalProperties)}`
  }
  if (Array.isArray(node.type)) {
    return node.type.join(' | ')
  }
  return node.type ?? 'object'
}

const propertyTable = ({ properties = {}, required = [] }: SchemaNode): string =>
  tableOf(
    ['Field', 'Type', 'Required', 'Description'],
    Object.entries(properties)
      .filter(([name]) => name !== '$schema')
      .map(([name, property]) => [
        `\`${name}\``,
        escapeCell(typeOf(property)),
        required.includes(name) ? 'yes' : '',
        escapeCell(property.description ?? ''),
      ]),
  )

const variantTitle = (variant: SchemaNode): string => {
  const [name, discriminator] =
    Object.entries(variant.properties ?? {}).find(([, property]) => property.const !== undefined) ??
    []
  if (variant.description !== undefined || discriminator === undefined) {
    return variant.description ?? typeOf(variant)
  }
  return `\`${name}\`: ${typeOf(discriminator)}`
}

const variantSection = (variant: SchemaNode): string[] =>
  variant.properties === undefined
    ? [`- ${typeOf(variant)}`]
    : ['', `**${variantTitle(variant)}**`, '', propertyTable(variant)]

const definitionSection = ([name, definition]: [string, SchemaNode]): string => {
  const variants = definition.anyOf ?? definition.oneOf ?? []
  const body =
    definition.properties === undefined
      ? variants.flatMap(variantSection)
      : ['', propertyTable(definition)]
  return [`## ${name}`, '', definition.description ?? '', ...body].join('\n')
}

const manifestPage = (): string => {
  const schema = readJson<RootSchema>(PLUGIN_SCHEMA_PATH)
  return pageOf({ title: 'Manifest reference', description: 'Every field of plugin.json.' }, [
    'The JSON schema ships as `create-next-suite/schemas/plugin.json`; point `$schema` at it for',
    'completion in your editor. The types of `create-next-suite/plugin` carry the same names and',
    'descriptions.',
    '',
    propertyTable(schema),
    '',
    Object.entries(schema.$defs ?? {})
      .map(definitionSection)
      .join('\n\n'),
  ])
}

const sections = readJson<Section[]>(CATEGORIES_PATH)
const manifests = loadManifests()
const optionSlugs = sections.map((section) => slugOf(section.section))
mkdirSync(OPTIONS_PATH, { recursive: true })
for (const section of sections) {
  writeFileSync(
    join(OPTIONS_PATH, `${slugOf(section.section)}.mdx`),
    sectionPage(section, manifests),
  )
}
writeFileSync(
  join(OPTIONS_PATH, 'meta.json'),
  `${JSON.stringify({ title: 'Options', pages: optionSlugs }, null, 2)}\n`,
)
writeFileSync(join(CONTENT_PATH, 'cli.mdx'), cliPage())
writeFileSync(join(CONTENT_PATH, 'plugins', 'manifest.mdx'), manifestPage())
