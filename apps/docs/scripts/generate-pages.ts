import { execFileSync } from 'node:child_process'
import { mkdirSync, readdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import packageJson from 'create-next-suite/package.json' with { type: 'json' }

/** Writes the docs pages that come from create-next-suite itself: its options and its CLI help. */

/** The fields of a category of create-next-suite these pages show. */
type Category = {
  id: string
  question: string
  section: string
  cardinality: 'one' | 'at-most-one' | 'many'
  default: string | string[] | null
}
/** The fields of a built-in plugin these pages show. */
type Plugin = { name: string; title: string; description?: string; category?: string }
type Section = { section: string; categories: Category[] }

const PACKAGE_ROOT = fileURLToPath(
  new URL('.', import.meta.resolve('create-next-suite/package.json')),
)
const CLI_PATH = join(PACKAGE_ROOT, packageJson.bin['create-next-suite'])
const CATEGORIES_PATH = join(PACKAGE_ROOT, 'src', 'plugin-definition', 'categories.ts')
const PLUGINS_PATH = join(PACKAGE_ROOT, 'plugins-v2')
const PLUGIN_FILE = 'plugin.ts'
const CONTENT_PATH = fileURLToPath(new URL('../content/docs/', import.meta.url))
const OPTIONS_PATH = join(CONTENT_PATH, 'options')
const NOTICE = '{/* Generated by scripts/generate-pages.ts from create-next-suite; do not edit. */}'

/** Imports a TypeScript module of create-next-suite, which Node.js runs by stripping its types. */
const importModule = async (path: string): Promise<Record<string, unknown>> =>
  import(pathToFileURL(path).href)

const escapeCell = (text: string): string => text.replaceAll('|', '\\|').replaceAll('\n', ' ')

const tableOf = (headers: string[], rows: string[][]): string =>
  [headers, headers.map(() => '---'), ...rows].map((cells) => `| ${cells.join(' | ')} |`).join('\n')

const pageOf = (frontmatter: { title: string; description: string }, body: string[]): string =>
  [
    '---',
    `title: ${frontmatter.title}`,
    `description: ${frontmatter.description}`,
    '---',
    '',
    NOTICE,
    '',
    ...body,
    '',
  ].join('\n')

/** The categories grouped by the section of the wizard that asks them, in the order it asks. */
const sectionsOf = (categories: readonly Category[]): Section[] =>
  [...new Set(categories.map((category) => category.section))].map((section) => ({
    section,
    categories: categories.filter((category) => category.section === section),
  }))

const loadCategories = async (): Promise<Category[]> =>
  (await importModule(CATEGORIES_PATH)).CATEGORIES as Category[]

const loadPlugins = async (): Promise<Plugin[]> =>
  Promise.all(
    readdirSync(PLUGINS_PATH).flatMap((group) =>
      readdirSync(join(PLUGINS_PATH, group)).map(
        async (name) =>
          (await importModule(join(PLUGINS_PATH, group, name, PLUGIN_FILE))).default as Plugin,
      ),
    ),
  )

const slugOf = (title: string): string => title.toLowerCase().replace(/[^a-z0-9]+/g, '-')

const defaultsOf = (category: Category): string[] => {
  if (Array.isArray(category.default)) {
    return category.default
  }
  return category.default === null ? [] : [category.default]
}

const flagOf = (category: Category): string =>
  category.cardinality === 'many' ? `--${category.id} <plugins>` : `--${category.id} <plugin>`

const categorySection = (category: Category, plugins: Plugin[]): string => {
  const defaults = defaultsOf(category)
  const rows = plugins
    .filter((plugin) => plugin.category === category.id)
    .map((plugin) => [
      `\`${plugin.name}\``,
      escapeCell(plugin.title),
      escapeCell(plugin.description ?? ''),
      defaults.includes(plugin.name) ? 'yes' : '',
    ])
  const noneHint = category.cardinality === 'one' ? '' : ` Pass \`--no-${category.id}\` for none.`
  return [
    `## ${category.question}`,
    '',
    `Flag: \`${flagOf(category)}\`.${noneHint}`,
    '',
    tableOf(['Plugin', 'Title', 'What it does', 'Default'], rows),
  ].join('\n')
}

const sectionPage = (section: Section, plugins: Plugin[]): string =>
  pageOf(
    {
      title: section.section,
      description: `The ${section.section} options of create-next-suite.`,
    },
    [section.categories.map((category) => categorySection(category, plugins)).join('\n\n')],
  )

const cliPage = (): string => {
  const help = execFileSync(process.execPath, [CLI_PATH, '--help'], {
    encoding: 'utf8',
    env: { ...process.env, NO_COLOR: '1' },
  })
  return pageOf({ title: 'CLI', description: 'The command line of create-next-suite.' }, [
    '```text',
    help.trimEnd(),
    '```',
  ])
}

const sections = sectionsOf(await loadCategories())
const plugins = await loadPlugins()
const optionSlugs = sections.map((section) => slugOf(section.section))
mkdirSync(OPTIONS_PATH, { recursive: true })
for (const section of sections) {
  writeFileSync(join(OPTIONS_PATH, `${slugOf(section.section)}.mdx`), sectionPage(section, plugins))
}
writeFileSync(
  join(OPTIONS_PATH, 'meta.json'),
  `${JSON.stringify({ title: 'Options', pages: optionSlugs }, null, 2)}\n`,
)
writeFileSync(join(CONTENT_PATH, 'cli.mdx'), cliPage())
