import { execFileSync } from 'node:child_process'
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

/** Writes the docs pages that come from create-next-suite itself: its options and its CLI help. */

type Category = { id: string; question: string; cardinality: string; default: unknown }
type Section = { section: string; categories: Category[] }
type Manifest = { name: string; title: string; description: string; category?: string }

const PACKAGE_URL = new URL('package.json', import.meta.resolve('create-next-suite/package.json'))
const PACKAGE_ROOT = fileURLToPath(new URL('.', PACKAGE_URL))
const CONTENT = fileURLToPath(new URL('../content/docs/', import.meta.url))
const OPTIONS = join(CONTENT, 'options')
const NOTICE = '{/* Generated by scripts/generate-pages.ts from create-next-suite; do not edit. */}'

const readJson = <Value>(path: string): Value => JSON.parse(readFileSync(path, 'utf8')) as Value

const loadManifests = (): Manifest[] => {
  const pluginsFolder = join(PACKAGE_ROOT, 'plugins')
  return readdirSync(pluginsFolder).flatMap((group) =>
    readdirSync(join(pluginsFolder, group)).map((plugin) =>
      readJson<Manifest>(join(pluginsFolder, group, plugin, 'plugin.json')),
    ),
  )
}

const slugOf = (title: string): string => title.toLowerCase().replace(/[^a-z0-9]+/g, '-')

const defaultsOf = (category: Category): string[] => {
  if (Array.isArray(category.default)) {
    return category.default.map(String)
  }
  return category.default === null ? [] : [String(category.default)]
}

const flagOf = (category: Category): string =>
  category.cardinality === 'many' ? `--${category.id} <plugins>` : `--${category.id} <plugin>`

const categoryPage = (category: Category, manifests: Manifest[]): string => {
  const plugins = manifests.filter((manifest) => manifest.category === category.id)
  const defaults = defaultsOf(category)
  const rows = plugins.map(
    (plugin) =>
      `| \`${plugin.name}\` | ${plugin.title} | ${plugin.description} | ${defaults.includes(plugin.name) ? 'yes' : ''} |`,
  )
  const none = category.cardinality === 'one' ? '' : ` Pass \`--no-${category.id}\` for none.`
  return [
    `## ${category.question}`,
    '',
    `Flag: \`${flagOf(category)}\`.${none}`,
    '',
    '| Plugin | Title | What it does | Default |',
    '| --- | --- | --- | --- |',
    ...rows,
  ].join('\n')
}

const sectionPage = (section: Section, manifests: Manifest[]): string =>
  [
    '---',
    `title: ${section.section}`,
    `description: The ${section.section} options of create-next-suite.`,
    '---',
    '',
    NOTICE,
    '',
    section.categories.map((category) => categoryPage(category, manifests)).join('\n\n'),
    '',
  ].join('\n')

const cliPage = (): string => {
  const help = execFileSync(
    process.execPath,
    [join(PACKAGE_ROOT, 'dist/create-next-suite.mjs'), '--help'],
    { encoding: 'utf8', env: { ...process.env, NO_COLOR: '1' } },
  )
  return [
    '---',
    'title: CLI',
    'description: The command line of create-next-suite.',
    '---',
    '',
    NOTICE,
    '',
    '```text',
    help.trimEnd(),
    '```',
    '',
  ].join('\n')
}

const sections = readJson<Section[]>(join(PACKAGE_ROOT, 'categories.json'))
const manifests = loadManifests()
mkdirSync(OPTIONS, { recursive: true })
for (const section of sections) {
  writeFileSync(join(OPTIONS, `${slugOf(section.section)}.mdx`), sectionPage(section, manifests))
}
writeFileSync(
  join(OPTIONS, 'meta.json'),
  `${JSON.stringify({ title: 'Options', pages: sections.map((section) => slugOf(section.section)) }, null, 2)}\n`,
)
writeFileSync(join(CONTENT, 'cli.mdx'), cliPage())
